// Write src/mcp/tax-data-registry.ts: a static map of every tax-data file.
//
// The API and MCP server run as Cloudflare Pages Functions, which have no
// filesystem, so readTaxDataFromDisk cannot discover the data there and a
// template-string import cannot be bundled. Each entry is a lazy import so a
// request loads only the federal file and the one state it asks for.
//
// Runs before every build. tests/unit/tax-data-registry.test.ts fails if the
// committed file falls out of step with src/data.

import { promises as fs } from "fs";
import path from "path";
import { format, resolveConfig } from "prettier";

const dataDirectory = path.join(process.cwd(), "src", "data");
const outputFile = path.join(
  process.cwd(),
  "src",
  "mcp",
  "tax-data-registry.ts",
);
const yearPattern = /^\d{4}$/;

async function main() {
  const years = (await fs.readdir(dataDirectory))
    .filter((entry) => yearPattern.test(entry))
    .sort((a, b) => parseInt(b, 10) - parseInt(a, 10));

  const entries: string[] = [];
  for (const year of years) {
    const states = (await fs.readdir(path.join(dataDirectory, year, "state")))
      .filter((file) => file.endsWith(".ts"))
      .map((file) => file.replace(/\.ts$/, ""))
      .sort();
    const stateLines = states
      .map(
        (state) => `${state}: () => import("@/data/${year}/state/${state}"),`,
      )
      .join("\n");
    entries.push(
      `"${year}": {
        federal: () => import("@/data/${year}/federal"),
        states: {
          ${stateLines}
        },
      },`,
    );
  }

  const source = `// Generated by scripts/generate-tax-data-registry.ts. Do not edit by hand;
// run \`npm run generate-tax-data-registry\` after adding a year or state.

import type { TaxData } from "@/types";

type Loader = () => Promise<{ default: TaxData }>;

export type YearRegistry = {
  federal: Loader;
  states: Record<string, Loader>;
};

export const TAX_DATA_REGISTRY: Record<string, YearRegistry> = {
  ${entries.join("\n")}
};

/** Newest first. */
export const YEARS = ${JSON.stringify(years)};

export const LATEST_YEAR = YEARS[0];
`;

  const config = (await resolveConfig(outputFile)) ?? {};
  const formatted = await format(source, { ...config, filepath: outputFile });
  await fs.writeFile(outputFile, formatted);
  console.log(`Wrote ${path.relative(process.cwd(), outputFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
