// Write src/data-loaders/registry.ts: a static map of every tax-data file.
//
// The API and MCP server run as Cloudflare Pages Functions, which have no
// filesystem, so readTaxDataFromDisk cannot discover the data there and a
// template-string import cannot be bundled. Each entry is a lazy import so a
// request loads only the federal file and the one state it asks for, and that
// state's sales tax file where the year has one.
//
// Runs before every build and dev server. tests/unit/tax-data-registry.test.ts
// fails if the committed file falls out of step with src/data.

import { promises as fs } from "fs";
import path from "path";
import { format, resolveConfig } from "prettier";

const dataDirectory = path.join(process.cwd(), "src", "data");
const outputFile = path.join(
  process.cwd(),
  "src",
  "data-loaders",
  "registry.ts",
);
const yearPattern = /^\d{4}$/;

/** State keys from the .ts files in a directory; none if it is missing. */
async function statesIn(directory: string): Promise<string[]> {
  const files = await fs.readdir(directory).catch(() => [] as string[]);
  return files
    .filter((file) => file.endsWith(".ts"))
    .map((file) => file.replace(/\.ts$/, ""))
    .sort();
}

async function main() {
  const years = (await fs.readdir(dataDirectory))
    .filter((entry) => yearPattern.test(entry))
    .sort((a, b) => parseInt(b, 10) - parseInt(a, 10));

  const entries: string[] = [];
  for (const year of years) {
    const states = await statesIn(path.join(dataDirectory, year, "state"));
    const stateLines = states
      .map(
        (state) => `${state}: () => import("@/data/${year}/state/${state}"),`,
      )
      .join("\n");
    const salesTaxStates = await statesIn(
      path.join(dataDirectory, year, "sales-tax", "state"),
    );
    const salesTaxLines = salesTaxStates
      .map(
        (state) =>
          `${state}: () => import("@/data/${year}/sales-tax/state/${state}"),`,
      )
      .join("\n");
    entries.push(
      `"${year}": {
        federal: () => import("@/data/${year}/federal"),
        states: {
          ${stateLines}
        },
        salesTax: {
          ${salesTaxLines}
        },
      },`,
    );
  }

  const source = `// Generated by scripts/generate-tax-data-registry.ts. Do not edit by hand;
// run \`npm run generate-tax-data-registry\` after adding a year or state.

import type { SalesTaxData, TaxData } from "@/types";

type Loader = () => Promise<{ default: TaxData }>;
type SalesTaxLoader = () => Promise<{ default: SalesTaxData }>;

export type YearRegistry = {
  federal: Loader;
  states: Record<string, Loader>;
  /** Empty for a year with no sales tax data. */
  salesTax: Record<string, SalesTaxLoader>;
};

export const TAX_DATA_REGISTRY: Record<string, YearRegistry> = {
  ${entries.join("\n")}
};

/** Newest first. */
export const YEARS = ${JSON.stringify(years)};

/**
 * The newest year we have tax data for.
 *
 * This is the app's single definition of "current year". Deliberately not
 * \`new Date().getFullYear()\` — the calendar rolls over on January 1st but the
 * data does not, and a mismatch between the two makes \`/\` and \`/{year}\` serve
 * identical pages while disagreeing about which one is canonical.
 */
export const LATEST_YEAR = YEARS[0];
`;

  const config = (await resolveConfig(outputFile)) ?? {};
  const formatted = await format(source, { ...config, filepath: outputFile });
  await fs.writeFile(outputFile, formatted);
  console.log(`Wrote ${path.relative(process.cwd(), outputFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
